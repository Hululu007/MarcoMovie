    private static boolean verifyEcdsaP256(
            byte[] pubKey65, byte[] payload, byte[] rBytes, byte[] sBytes) {
        try {
            byte[] spki = new byte[P256_SPKI_PREFIX.length + pubKey65.length];
            System.arraycopy(P256_SPKI_PREFIX, 0, spki, 0, P256_SPKI_PREFIX.length);
            System.arraycopy(pubKey65, 0, spki, P256_SPKI_PREFIX.length, pubKey65.length);
            PublicKey publicKey =
                    KeyFactory.getInstance("EC").generatePublic(new X509EncodedKeySpec(spki));
            byte[] derSig = rawRsToDer(rBytes, sBytes);
            Signature verifier = Signature.getInstance("SHA256withECDSA");
            verifier.initVerify(publicKey);
            verifier.update(DOMAIN_SEP.getBytes(StandardCharsets.UTF_8));
            verifier.update(payload);
            return verifier.verify(derSig);
        } catch (Exception e) {
            return false;
        }
    }

    static byte[] rawRsToDer(byte[] r, byte[] s) {
        byte[] rDer = encodeAsn1Integer(r);
        byte[] sDer = encodeAsn1Integer(s);
        int seqLen = rDer.length + sDer.length;
        ByteArrayOutputStream out = new ByteArrayOutputStream(seqLen + 4);
        out.write(0x30);
        if (seqLen < 128) {
            out.write(seqLen);
        } else {
            out.write(0x81);
            out.write(seqLen);
        }
        out.write(rDer, 0, rDer.length);
        out.write(sDer, 0, sDer.length);
        return out.toByteArray();
    }

    private static byte[] encodeAsn1Integer(byte[] unsignedBigEndian) {
        int start = 0;
        while (start < unsignedBigEndian.length - 1 && unsignedBigEndian[start] == 0) {
            start++;
        }
        boolean needsLeadingZero = (unsignedBigEndian[start] & 0x80) != 0;
        int len = unsignedBigEndian.length - start + (needsLeadingZero ? 1 : 0);
        byte[] out = new byte[2 + len];
        out[0] = 0x02;
        out[1] = (byte) len;
        int dst = 2;
        if (needsLeadingZero) {
            out[dst++] = 0x00;
        }
        System.arraycopy(unsignedBigEndian, start, out, dst, unsignedBigEndian.length - start);
        return out;
    }

    static String stripWhitespace(String s) {
        if (s == null) return "";
        StringBuilder sb = new StringBuilder(s.length());
        for (int i = 0; i < s.length(); i++) {
            char c = s.charAt(i);
            if (!Character.isWhitespace(c)) sb.append(c);
        }
        return sb.toString();
    }

    static byte[] hexToBytes(String hex) {
        if (hex == null || (hex.length() & 1) != 0) return new byte[0];
        int len = hex.length() / 2;
        byte[] out = new byte[len];
        for (int i = 0; i < len; i++) {
            int hi = Character.digit(hex.charAt(i * 2), 16);
            int lo = Character.digit(hex.charAt(i * 2 + 1), 16);
            if (hi < 0 || lo < 0) return new byte[0];
            out[i] = (byte) ((hi << 4) | lo);
        }
        return out;
    }

    /** Pure-JVM Base64URL decoder (no {@code android.util.Base64} or API 26 dependency). */
    static byte[] base64UrlDecode(String input) {
        if (input == null || input.isEmpty()) return null;
        int len = input.length();
        while (len > 0 && input.charAt(len - 1) == '=') len--;
        if ((len & 3) == 1) return null;
        int outLen = (len * 3) / 4;
        byte[] out = new byte[outLen];
        int outPos = 0;
        int i = 0;
        while (i < len) {
            int c0 = b64Val(input.charAt(i++));
            int c1 = i < len ? b64Val(input.charAt(i++)) : -1;
            int c2 = i < len ? b64Val(input.charAt(i++)) : -2;
            int c3 = i < len ? b64Val(input.charAt(i++)) : -2;
            if (c0 < 0 || c1 < 0 || c2 == -1 || c3 == -1) return null;
            int triple = (c0 << 18) | (c1 << 12) | ((c2 >= 0 ? c2 : 0) << 6) | (c3 >= 0 ? c3 : 0);
            if (outPos < outLen) out[outPos++] = (byte) ((triple >> 16) & 0xFF);
            if (c2 >= 0 && outPos < outLen) out[outPos++] = (byte) ((triple >> 8) & 0xFF);
            if (c3 >= 0 && outPos < outLen) out[outPos++] = (byte) (triple & 0xFF);
        }
        return out;
    }

    private static int b64Val(char c) {
        if (c >= 'A' && c <= 'Z') return c - 'A';
        if (c >= 'a' && c <= 'z') return c - 'a' + 26;
        if (c >= '0' && c <= '9') return c - '0' + 52;
        if (c == '-' || c == '+') return 62;
        if (c == '_' || c == '/') return 63;
        return -1;
    }
